#!/usr/bin/env python3
"""O5/O10 consumer seam: actual batch template → fleet and triage readers.

Runs only the two existing batch cases and the affected triage shape cases.
All endpoints are synthetic. The O10 source is the carried skills/triage
beside this skill, so a release tree without Git history runs it; with
--o10-revision it is extracted at that explicit pin instead. No checkout,
branch merge, publication, or live command is performed.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tempfile
import types

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--o10-revision')
args = parser.parse_args()
pin = None
if args.o10_revision:
    pin = subprocess.check_output(['git', 'rev-parse', args.o10_revision + '^{commit}'], cwd=ROOT, text=True).strip()
print('O10 source:', pin or 'carried skills/triage', flush=True)


def o10_source(relative):
    if pin is None:
        return (ROOT / 'skills/triage' / relative).read_bytes()
    return subprocess.check_output(['git', 'show', pin + ':skills/triage/' + relative], cwd=ROOT)


with tempfile.TemporaryDirectory(prefix='1273-o10-') as directory:
    root = Path(directory)
    scripts = root / 'skills/launch-fleet/scripts'
    shutil.copytree(HERE, scripts, ignore=shutil.ignore_patterns('__pycache__'))
    triage = root / 'skills/triage'
    for relative in ['SKILL.md', 'find-work.sh', 'test/test_find_work.py', 'test/fake_gh.py']:
        target = triage / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(o10_source(relative))
    revision = root / 'skills/to-tickets/revision.sh'
    revision.parent.mkdir(parents=True)
    revision.write_bytes((HERE.parent.parent / 'to-tickets/revision.sh').read_bytes())

    source = (scripts / 'test.sh').read_text()
    prefix = source[:source.index('# A full run: the workers')]
    prefix = re.sub(r'^HERE=.*$', 'HERE=' + shlex.quote(str(scripts)), prefix, count=1, flags=re.M)
    begin = source.index('### Batch approval (#1463):')
    end = source.index('### Follow-ups filed outside the spec', begin)
    captured = root / 'batch-world.json'
    footer = '\ncp "$last/world.json" ' + shlex.quote(str(captured)) + ''' || exit 1
[ "$cases" = 2 ] || bad 'the batch cases ran' "$cases cases ran, not 2"
printf '%s fleet batch cases, %s failed\n' "$cases" "$fails"
[ "$fails" = 0 ]
'''
    script = root / 'batch.sh'
    script.write_text(prefix + source[begin:end] + footer)
    env = {k: v for k, v in os.environ.items() if not k.startswith(('TEST_', 'FLEET_SH', 'FAKE_GH_', 'LAUNCH_FLEET_'))}
    result = subprocess.run(['sh', str(script)], cwd=root, env=env)
    if result.returncode:
        raise SystemExit(result.returncode)
    world = json.loads(captured.read_text())
    rendered = {n: next(i for i in world['issues'] if i['number'] == n)['comments'][-1]['body'] for n in (16, 17)}
    for body in rendered.values():
        lines = body.splitlines()
        assert lines[0].startswith('**Approved on its own by Robin, 2026-11-01:** ')
        assert not any(c in lines[0] for c in '\"“”')
        assert re.fullmatch(r'Private record: https://github\.com/jparker2006/ClosedWiz/(issues|pull)/[1-9][0-9]*#issuecomment-[1-9][0-9]*', lines[1])
        assert lines[2:4] == ['', '> *This was generated by AI during triage.*']
        assert not re.search(r'<[^>]+>|\bthr_[A-Za-z0-9]', body)

    # Reuse O10's real fake endpoint and its owning shape table; do not execute
    # unrelated collector cases or instruction tests from that module's footer.
    fixture = triage / 'test/test_find_work.py'
    module = types.ModuleType('o10_consumer')
    module.__file__ = str(fixture)
    definitions = fixture.read_text().split('\nmain()\n')[0]
    exec(compile(definitions, str(fixture), 'exec'), module.__dict__)
    case, what, issues, fault, labels, tools, code, expected, _ = module.CASES[0]
    issues = copy.deepcopy(issues)
    # This is the producer's actual rendered record, replacing only O10's
    # positive input; its existing pasted/missing/malformed cases stay intact.
    next(i for i in issues if i['number'] == 924)['comments'] = [rendered[16]]
    result = module.run(case, issues, fault, labels, tools)
    assert result.returncode == code == 0, result.stderr
    assert result.stdout.splitlines() == expected, result.stdout
    assert result.stderr == '', result.stderr
    print('ok   O10 F1: rendered approval quiet; pasted/missing/malformed shapes remain work', flush=True)

    body = rendered[16]
    pointer = body.splitlines()[1]
    marker = '> *This was generated by AI during triage.*'
    inputs = [
        ('rendered approval', body, ''),
        ('pasted approval', 'Pasted record:\n' + body, '#16 to sort: Synthetic consumer 16\n'),
        ('missing pointer', body.replace(pointer + '\n', ''), '#16 to sort: Synthetic consumer 16\n'),
        ('malformed pointer', body.replace(pointer, 'Private record: not-a-pointer'), '#16 to sort: Synthetic consumer 16\n'),
        ('file pointer', body.replace(pointer, 'Private record: https://github.com/jparker2006/ClosedWiz/blob/main/synthetic.md'), '#16 to sort: Synthetic consumer 16\n'),
        ('leading-zero pointer', body.replace('/issues/9001#', '/issues/09001#'), '#16 to sort: Synthetic consumer 16\n'),
        ('missing marker', body.replace(marker, ''), '#16 to sort: Synthetic consumer 16\n'),
        ('unrelated later marker', body.replace('\n\n' + marker, '\nUnrelated text.\n\n' + marker), '#16 to sort: Synthetic consumer 16\n'),
    ]
    for name, value, expected in inputs:
        issue = module.issue(16, title='Synthetic consumer 16', labels=['needs-triage'], comments=[value])
        result = module.run(name, [issue], None, module.DEFAULT, 'all')
        assert result.returncode == 0 and result.stderr == '', (name, result.stderr)
        assert result.stdout == expected, (name, result.stdout)
        print('ok   triage consumer:', name, flush=True)
    print('2 fleet batch cases, 1 existing O10 shape table, 8 rendered-record cases passed', flush=True)
